package com.rndmodgames.futtoboru.engine.temporal;

import java.time.DayOfWeek;
import java.time.LocalDate;
import java.time.LocalDateTime;
import java.time.LocalTime;
import java.time.MonthDay;
import java.time.temporal.TemporalAdjusters;
import java.util.ArrayList;
import java.util.Collections;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Set;

import com.rndmodgames.futtoboru.data.Club;
import com.rndmodgames.futtoboru.data.Match;
import com.rndmodgames.futtoboru.system.Log;
import com.rndmodgames.futtoboru.system.SaveGame;

/**
 * P2-11: the era calendar of a season, the rules the generated schedule follows (decision D17: the dates are
 * generated by these rules; the real 1888-89 fixture dates in docs/data are reference data, never read here).
 * P2-14: the rules are data, the {@code calendar} block of {@code season.json} ({@link CalendarRules}); a season
 * without one keeps the latest earlier season's rules, a game without data the 1888-89 defaults below.
 *
 * <ul>
 * <li>League: Saturdays from the first Saturday on or after 8 September to the last Saturday on or before
 * 20 April of the next year, spread evenly; never on a cup Saturday or Christmas Day. Only when the
 * Saturdays run out (a big league) are midweek dates (Wednesdays) added.</li>
 * <li>FA Cup: opens with the qualifying rounds (first Saturday of October); the proper rounds are drawn from the
 * first Monday of January (placeholder), each later round after the one before is decided. Proper rounds on
 * Saturdays two weeks apart, the final on the last Saturday of March and the rounds before it back to the first
 * Saturday of February (5 rounds: Feb, Feb, Mar, Mar, final). A larger bracket plays its earlier rounds on
 * Wednesdays two weeks apart in December and January, which the league never uses.</li>
 * <li>Replays: the following Saturday when both clubs are free, else midweek (Wednesday first) of the week
 * after the tie, always before the next round.</li>
 * </ul>
 *
 * A date belongs to the season starting that year from April on (the game opens in April 1888, before the league
 * is founded on 17 April), else to the season of the year before.
 *
 * <p>The cup methods use the season's first cup calendar (the FA Cup) unless {@link #withCup(String)} picks another.
 */
public final class SeasonCalendar {

    public static final LocalTime KICK_OFF = LocalTime.of(15, 0);

    private final int startYear;
    private final CalendarRules rules;
    private final CalendarRules.Cup cup;

    private SeasonCalendar(int startYear, CalendarRules rules, CalendarRules.Cup cup) {
        this.startYear = startYear;
        this.rules = rules;
        this.cup = cup;
    }

    public static SeasonCalendar forSeason(int startYear) {
        CalendarRules rules = CalendarRules.forSeason(startYear);
        return new SeasonCalendar(startYear, rules, rules.cup(null));
    }

    /** The calendar of the season a date belongs to (April 1888 to March 1889 = 1888-89) */
    public static SeasonCalendar forDate(LocalDateTime date) {
        return forDate(date.toLocalDate());
    }

    public static SeasonCalendar forDate(LocalDate date) {
        return forSeason(startYearOf(date));
    }

    /** The season a date belongs to: from April on the season starting that year, else the year before */
    public static int startYearOf(LocalDate date) {
        return date.getMonthValue() >= CalendarRules.SEASON_TURNS.getValue() ? date.getYear() : date.getYear() - 1;
    }

    /** The same season with the cup methods on the calendar of one cup competition (data id; null = the first) */
    public SeasonCalendar withCup(String competitionDataId) {
        return new SeasonCalendar(startYear, rules, rules.cup(competitionDataId));
    }

    public int getStartYear() {
        return startYear;
    }

    /** First league Saturday: the first Saturday on or after 8 September (8 Sep 1888) */
    public LocalDate leagueOpening() {
        return rules.leagueOpens.in(startYear);
    }

    /** Last league Saturday: the last Saturday on or before 20 April of the next year (20 Apr 1889) */
    public LocalDate leagueClosing() {
        return rules.leagueCloses.in(startYear);
    }

    // ------------------------------------------------------------------------------------------------ cups

    /** The day the cup opens (its edition starts and its creation script runs): 6 Oct 1888 */
    public LocalDate cupOpens() {
        return cup.opens.in(startYear);
    }

    /** The first day the cup's first round may be drawn: 7 Jan 1889 (placeholder) */
    public LocalDate cupFirstDraw() {
        LocalDate draw = cup.firstDraw.in(startYear);
        return draw.isBefore(cupOpens()) ? cupOpens() : draw;
    }

    /** True when each later round is drawn after the round before is decided (else the first draw's bracket) */
    public boolean isOpenDraw() {
        return cup.openDraw;
    }

    /** A later round is drawn at the earliest this many days after the date of the round before */
    public int drawDaysAfterRound() {
        return cup.drawDaysAfterRound;
    }

    /** The cup final: the last Saturday of March of the next year (30 Mar 1889) */
    public LocalDate cupFinal() {
        return cup.finalDay.in(startYear);
    }

    /** The proper-round Saturdays, earliest first: two weeks apart, from the final back to the first one in February */
    public List<LocalDate> cupSaturdays() {
        List<LocalDate> dates = new ArrayList<>();
        MonthDay from = cup.properFrom;
        LocalDate first = from.atYear(CalendarRules.yearOf(from.getMonth(), startYear));
        for (LocalDate d = cupFinal(); !d.isBefore(first); d = d.minusDays(cup.daysBetweenRounds)) {
            dates.add(d);
        }
        if (dates.isEmpty()) {
            dates.add(cupFinal()); // a properFrom after the final: the final alone
        }
        Collections.reverse(dates);
        return dates;
    }

    /** Midweek dates of the rounds before the proper window, earliest first (Wednesdays, two weeks apart) */
    List<LocalDate> earlyCupWednesdays(int count) {
        List<LocalDate> dates = new ArrayList<>();
        LocalDate d = cupSaturdays().get(0).minusDays(1).with(TemporalAdjusters.previousOrSame(cup.earlyRoundsOn));
        for (int i = 0; i < count; i++) {
            dates.add(d);
            d = d.minusDays(cup.daysBetweenRounds);
        }
        Collections.reverse(dates);
        return dates;
    }

    /** The dates of a cup of the given number of rounds, first round first; the last is the final */
    public List<LocalDateTime> cupRoundDates(int rounds) {
        List<LocalDate> saturdays = cupSaturdays();
        List<LocalDate> dates = new ArrayList<>();
        if (rounds > saturdays.size()) {
            int early = rounds - saturdays.size();
            if (early > cup.maxEarlyRounds) {
                Log.warn(Log.ENGINE_SCHEDULING, "SeasonCalendar", rounds + " cup rounds; the earliest "
                        + (early - cup.maxEarlyRounds) + " share the first midweek date");
            }
            List<LocalDate> wednesdays = earlyCupWednesdays(Math.max(1, Math.min(early, cup.maxEarlyRounds)));
            for (int i = early; i > wednesdays.size(); i--) {
                dates.add(wednesdays.get(0));
            }
            dates.addAll(wednesdays);
            dates.addAll(saturdays);
        } else {
            dates.addAll(saturdays.subList(saturdays.size() - rounds, saturdays.size()));
        }
        List<LocalDateTime> out = new ArrayList<>();
        for (LocalDate d : dates) {
            out.add(d.atTime(KICK_OFF));
        }
        return out;
    }

    /** The first cup date of this season after the given day (proper Saturdays, then early Wednesdays), or null */
    public LocalDateTime nextCupDateAfter(LocalDate day) {
        List<LocalDate> all = new ArrayList<>(earlyCupWednesdays(cup.maxEarlyRounds));
        all.addAll(cupSaturdays());
        for (LocalDate d : all) {
            if (d.isAfter(day)) {
                return d.atTime(KICK_OFF);
            }
        }
        return null;
    }

    /**
     * Dates the league keeps free: every cup's dates, the midweek after each cup Saturday (replays) and the days the
     * calendar names (Christmas Day)
     */
    Set<LocalDate> leagueBlockedDates() {
        Set<LocalDate> blocked = new LinkedHashSet<>();
        for (String competition : rules.cups.isEmpty() ? List.of("") : rules.cups.keySet()) {
            SeasonCalendar c = withCup(competition.isEmpty() ? null : competition);
            blocked.addAll(c.cupSaturdays());
            blocked.addAll(c.earlyCupWednesdays(c.cup.maxEarlyRounds));
            for (LocalDate saturday : c.cupSaturdays()) {
                for (int d = 2; d <= 5; d++) { // Monday to Thursday after the tie
                    blocked.add(saturday.plusDays(d));
                }
            }
        }
        for (MonthDay day : rules.noLeagueOn) {
            blocked.add(day.atYear(CalendarRules.yearOf(day.getMonth(), startYear)));
        }
        return blocked;
    }

    /**
     * The league match days: {@code count} dates spread evenly over the league Saturdays from {@code notBefore}
     * (or the opening, whichever is later) to the closing. When there are too few Saturdays, Wednesdays of the same
     * window are added; when even those run out, Saturdays after the closing.
     */
    public List<LocalDateTime> leagueMatchDays(int count, LocalDate notBefore) {
        DayOfWeek matchDay = rules.leagueOpens.weekday;
        LocalDate from = leagueOpening();
        if (notBefore != null && notBefore.isAfter(from)) {
            from = notBefore.with(TemporalAdjusters.nextOrSame(matchDay));
        }
        LocalDate to = leagueClosing();
        Set<LocalDate> blocked = leagueBlockedDates();

        List<LocalDate> candidates = new ArrayList<>();
        for (LocalDate d = from; !d.isAfter(to); d = d.plusWeeks(1)) {
            if (!blocked.contains(d)) {
                candidates.add(d);
            }
        }
        if (candidates.size() < count) {
            Log.warn(Log.ENGINE_SCHEDULING, "SeasonCalendar", count + " league match days but " + candidates.size()
                    + " free Saturdays; adding midweek dates");
            for (LocalDate d = from.with(TemporalAdjusters.nextOrSame(rules.midweek)); !d.isAfter(to)
                    && candidates.size() < count; d = d.plusWeeks(1)) {
                if (!blocked.contains(d)) {
                    candidates.add(d);
                }
            }
            Collections.sort(candidates);
        }
        for (LocalDate d = to.plusWeeks(1); candidates.size() < count; d = d.plusWeeks(1)) {
            if (!blocked.contains(d)) {
                candidates.add(d);
            }
        }

        // spread evenly, first and last candidate included
        List<LocalDateTime> days = new ArrayList<>();
        int n = candidates.size();
        for (int i = 0; i < count; i++) {
            int index = count == 1 ? 0 : (int) Math.round((double) i * (n - 1) / (count - 1));
            days.add(candidates.get(index).atTime(KICK_OFF));
        }
        return days;
    }

    /** End of the league season: the closing day, end of day */
    public LocalDateTime leagueEnd() {
        return leagueClosing().atTime(23, 59);
    }

    /** The cup edition runs until a month after the final (room for a final replay) */
    public LocalDateTime cupEnd() {
        return cupFinal().plusMonths(1).atTime(23, 59);
    }

    /**
     * The replay of a drawn tie played on {@code tieDate}: the following Saturday (the same weekday a week later)
     * when both clubs are free, else midweek of the week after (Wednesday, Thursday, Tuesday, Monday, Friday),
     * never on or after {@code before} (the next round, may be null) nor before {@code today}.
     */
    public static LocalDateTime replayDate(SaveGame game, Match tie, LocalDate today, LocalDate before) {
        LocalDate tieDay = tie.getMatchDateTime() != null ? tie.getMatchDateTime().toLocalDate() : today;
        LocalDate base = tieDay.isBefore(today) ? today : tieDay;
        int[] offsets = { 7, 4, 5, 3, 2, 6 };
        for (int offset : offsets) {
            LocalDate d = base.plusDays(offset);
            if (before != null && !d.isBefore(before)) {
                continue;
            }
            if (isFree(game, tie.getHomeClubId(), d) && isFree(game, tie.getAwayClubId(), d)) {
                return d.atTime(KICK_OFF);
            }
        }
        Log.warn(Log.ENGINE_SCHEDULING, "SeasonCalendar", "No free day for the replay of match " + tie.getId()
                + " in the week after " + tieDay + "; playing it a week later");
        return base.plusDays(7).atTime(KICK_OFF);
    }

    /** No match of the club (as home or away club) on that day */
    public static boolean isFree(SaveGame game, Long clubId, LocalDate day) {
        if (game == null || clubId == null) {
            return true;
        }
        Club club = game.getClubById(clubId);
        if (club == null) {
            return true;
        }
        return !hasMatchOn(club.getScheduledMatches(), clubId, day) && !hasMatchOn(club.getPlayedMatches(), clubId, day);
    }

    private static boolean hasMatchOn(List<Match> matches, Long clubId, LocalDate day) {
        if (matches == null) {
            return false;
        }
        for (Match m : matches) {
            if (m != null && m.getMatchDateTime() != null && m.getMatchDateTime().toLocalDate().equals(day)
                    && (clubId.equals(m.getHomeClubId()) || clubId.equals(m.getAwayClubId()))) {
                return true;
            }
        }
        return false;
    }
}
